#!/usr/bin/env node
/**
 * Generates the static `public/theme.css` from `src/config.json` +
 * the font theme map. Mirrors the three inline `<style>` blocks that
 * the layout used to emit on every page:
 *
 *   1. `[data-distro]{display:none}` and per-theme visibility toggles.
 *   2. `--color-*` variables per theme.
 *   3. `--font-mono` per theme.
 *
 * Moving them out of the head saves ~25 KB per page and lets the
 * browser cache the CSS across pages.
 *
 * Re-run whenever `src/config.json` or `src/lib/themes.ts` change:
 *   node tools/generate-theme-css.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

const config = JSON.parse(
	readFileSync(resolve(root, "src/config.json"), "utf8"),
);

/**
 * Same map as `src/lib/fonts.ts → FONT_FAMILY`. Kept in sync by hand —
 * the only way to avoid the duplication is to import the TS module,
 * which requires a build step (out of scope for a one-off generator).
 */
const FONT_FAMILY = {
	"JetBrains Mono": "JetBrains Mono",
	"Ubuntu Mono": "Ubuntu Mono",
	Hack: "Fira Code",
	Inter: "Inter",
	"Noto Sans": "Noto Sans",
	"Noto Sans Mono": "Noto Sans Mono",
	"Roboto Mono": "Roboto Mono",
	"Iosevka Term": "JetBrains Mono",
	"DejaVu Sans Mono": "JetBrains Mono",
	"Liberation Mono": "JetBrains Mono",
	"Cascadia Mono": "JetBrains Mono",
	"SF Mono": "JetBrains Mono",
	Monospace: "JetBrains Mono",
	Cantarell: "Inter",
};

function fontStack(family) {
	return `'${family}', ui-monospace, 'SF Mono', Menlo, Monaco, monospace`;
}

const themes = config.systems.map((s) => s.slug).sort();

const distroVisibilityCss = [
	"[data-distro]{display:none}",
	...themes.map(
		(slug) => `[data-theme="${slug}"] [data-distro="${slug}"]{display:revert}`,
	),
].join("");

const themeColorsCss = config.systems
	.map(
		(s) =>
			`[data-theme="${s.slug}"]{--color-bg:${s.colors.bg};--color-panel:${s.colors.panel};--color-border:${s.colors.border};--color-fg:${s.colors.fg};--color-dim:${s.colors.dim};--color-accent:${s.colors.accent};--color-c1:${s.colors.c1};--color-c2:${s.colors.c2};--color-c3:${s.colors.c3};}`,
	)
	.join("");

const themeFontsCss = config.systems
	.map(
		(s) =>
			`[data-theme="${s.slug}"]{--font-mono:${fontStack(FONT_FAMILY[s.font])};}`,
	)
	.join("");

const css = [
	"/* Generated by tools/generate-theme-css.mjs. Do not edit by hand. */",
	distroVisibilityCss,
	themeColorsCss,
	themeFontsCss,
].join("\n");

const out = resolve(root, "public/theme.css");
writeFileSync(out, css);
console.log(`Wrote ${out} (${css.length} bytes, ${themes.length} themes)`);
